"""Write the N64Recomp symbols file (syms/kig.us.syms.toml) from the function list and library names.

Inputs:  build/kig_funcs.csv (tools/kig_funcs.py), syms/libultra_symbols.txt (tools/kig_libsyms.py),
         syms/overrides.toml ([[rename]] section/vram/name/reason)
Output:  syms/kig.us.syms.toml: one [[section]] per code section (tools/kig_layout.py), with `rom`
         pointing into build/kig.recomp.z64.
Usage:   python tools/gen_syms.py
"""
import collections
import csv
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kig_layout import ROOT, SEGS  # noqa: E402

C_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main() -> int:
    libnames = {}
    for line in (ROOT / "syms" / "libultra_symbols.txt").read_text().splitlines():
        m = re.match(r"(\w+) = 0x([0-9A-F]+); // type:func segment:(\w+)", line)
        if m:
            libnames[(m[3], int(m[2], 16))] = m[1]
    ov_path = ROOT / "syms" / "overrides.toml"
    ov = tomllib.loads(ov_path.read_text(encoding="utf-8")) if ov_path.exists() else {}
    for e in ov.get("rename", []):
        libnames[(e["section"], e["vram"])] = e["name"]

    funcs = collections.defaultdict(list)
    for r in csv.DictReader(open(ROOT / "build" / "kig_funcs.csv")):
        v = int(r["vram"], 16)
        name = libnames.get((r["section"], v), r["name"])
        funcs[r["section"]].append((v, int(r["size"], 16), name))

    errors = []
    names = collections.Counter(n for fl in funcs.values() for _, _, n in fl)
    for n, c in names.items():
        if c > 1:
            errors.append(f"duplicate name {n}")
        if not C_IDENT.match(n):
            errors.append(f"bad identifier {n}")

    lines = ["# N64Recomp symbols file for Killer Instinct Gold (US Rev 2). Generated by tools/gen_syms.py; do not edit.",
             "# rom offsets refer to build/kig.recomp.z64 (tools/build_recomp_rom.py), not the original ROM.", ""]
    for s in SEGS:
        fl = sorted(funcs[s.name])
        for v, size, n in fl:
            if v + size > s.text_end:
                errors.append(f"{n} runs past {s.name} text")
        lines += ["[[section]]", f'name = "{s.name}"', f"rom = 0x{s.recomp_rom:X}", f"vram = 0x{s.vram:08X}",
                  f"size = 0x{s.size:X}", "", "functions = ["]
        lines += [f'    {{ name = "{n}", vram = 0x{v:08X}, size = 0x{size:X} }},' for v, size, n in fl]
        lines += ["]", ""]
    (ROOT / "syms" / "kig.us.syms.toml").write_text("\n".join(lines), encoding="utf-8")
    total = sum(len(fl) for fl in funcs.values())
    print(f"{total} functions ({sum(1 for k in libnames if k[0] in funcs)} named) -> syms/kig.us.syms.toml")
    for e in errors:
        print("  error:", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
