"""Name KI Gold's library functions (libultra 2.0D, libaudio) by matching them against the ones
W.G. 3D Hockey: Recompiled already identified (same SDK, same compiler).

Each function becomes a sequence of (mnemonic, register fields), with immediates and jump targets
ignored. A KI Gold function gets a wg3d name when its sequence equals exactly one wg3d named
function's. Near matches (difflib ratio >= 0.97, same length +-2) are listed for review only.

Inputs:  build/kig_funcs.csv, build/kig.recomp.z64,
         ../wg3d-recomp/baserom.us.z64 + ../wg3d-recomp/syms/wg3d.us.syms.toml (or WG3D_DIR)
         syms/libnames_manual.toml ([[name]] section/vram/name/reason) for hand identifications
Outputs: syms/libultra_symbols.txt (splat symbol_addrs format), docs/libsyms_report.md
Usage:   python tools/kig_libsyms.py
"""
import csv
import difflib
import os
import struct
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

import rabbitizer

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kig_layout import BY_NAME, ROOT, recomp_rom  # noqa: E402

WG3D = Path(os.environ.get("WG3D_DIR", ROOT.parent / "wg3d-recomp"))
WG3D_ROM_OFF, WG3D_VRAM = 0x1000, 0x80001C00


def sig(words) -> tuple:
    out = []
    for w in words:
        i = rabbitizer.Instruction(w)
        n = i.getOpcodeName()
        regs = []
        for f in ("rs", "rt", "rd"):
            try:
                if getattr(i, f"has_{f}")() if hasattr(i, f"has_{f}") else False:
                    regs.append(getattr(i, f).value)
            except Exception:
                pass
        if not regs:
            regs = [(w >> 21) & 31, (w >> 16) & 31] if n not in ("j", "jal") else []
            if (w >> 26) == 0:
                regs.append((w >> 11) & 31)
        out.append((n, tuple(regs)))
    return tuple(out)


def words_of(rom: bytes, off: int, size: int):
    return struct.unpack(f">{size // 4}I", rom[off:off + size])


def main() -> int:
    wrom = (WG3D / "baserom.us.z64").read_bytes()
    wsyms = tomllib.loads((WG3D / "syms" / "wg3d.us.syms.toml").read_text(encoding="utf-8"))
    ref = defaultdict(set)   # sig -> names
    ref_list = []
    for sec in wsyms["section"]:
        for f in sec["functions"]:
            if f["name"].startswith("func_") or f["size"] < 8:
                continue
            s = sig(words_of(wrom, f["vram"] - WG3D_VRAM + WG3D_ROM_OFF, f["size"]))
            ref[s].add(f["name"])
            ref_list.append((f["name"], s))

    rom = recomp_rom()
    rows = list(csv.DictReader(open(ROOT / "build" / "kig_funcs.csv")))
    named, near = {}, []
    used = defaultdict(list)
    for r in rows:
        if r["section"] not in ("boot", "seg0"):
            continue
        seg = BY_NAME[r["section"]]
        v, size = int(r["vram"], 16), int(r["size"], 16)
        s = sig(words_of(rom, seg.recomp_rom + v - seg.vram, size))
        hits = ref.get(s)
        if hits and len(hits) == 1:
            name = next(iter(hits))
            named[(r["section"], v)] = (name, "exact")
            used[name].append(v)
        elif size >= 0x20:
            best = max(((difflib.SequenceMatcher(None, s, rs, autojunk=False).ratio(), n)
                        for n, rs in ref_list if abs(len(rs) - len(s)) <= 2), default=(0, ""))
            if best[0] >= 0.97:
                near.append((r["section"], v, best[1], best[0]))
    # A name matched more than once (e.g. two identical tiny library functions): keep none.
    for name, vs in used.items():
        if len(vs) > 1:
            for k in [k for k, (n, _) in named.items() if n == name]:
                del named[k]
    man_path = ROOT / "syms" / "libnames_manual.toml"
    manual = tomllib.loads(man_path.read_text(encoding="utf-8")).get("name", []) if man_path.exists() else []
    for m in manual:
        named[(m["section"], m["vram"])] = (m["name"], "manual: " + m.get("reason", ""))

    lines = ["// Library function names (tools/kig_libsyms.py). splat symbol_addrs format.\n"]
    for (secname, v), (n, how) in sorted(named.items(), key=lambda x: x[0][1]):
        lines.append(f"{n} = 0x{v:08X}; // type:func segment:{secname} {how}\n")
    (ROOT / "syms" / "libultra_symbols.txt").write_text("".join(lines), encoding="utf-8")
    md = ["# Library names — Killer Instinct Gold", "", "Generated by `tools/kig_libsyms.py`.", "",
          f"- Exact matches against wg3d's library: {sum(1 for _, h in named.values() if h == 'exact')}",
          f"- Manual: {len(manual)}", f"- Near matches to review: {len(near)}", "",
          "| Section | VRAM | Name | How |", "|---|---|---|---|"]
    md += [f"| {s} | `{v:08X}` | {n} | {h} |" for (s, v), (n, h) in sorted(named.items(), key=lambda x: x[0][1])]
    md += ["", "## Near matches (not applied)", "", "| Section | VRAM | Closest | Ratio |", "|---|---|---|---|"]
    md += [f"| {s} | `{v:08X}` | {n} | {r:.3f} |" for s, v, n, r in near]
    (ROOT / "docs" / "libsyms_report.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(named)} names ({len(manual)} manual), {len(near)} near matches -> syms/libultra_symbols.txt, docs/libsyms_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
