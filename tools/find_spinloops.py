"""Find busy-wait loops: short backward loops that only load and compare (no stores, no calls).

On the N64 such a loop ends when an interrupt or another thread changes the polled memory; ultramodern
only switches threads inside OS calls, so each one needs a yield (kig_spin_yield) at its head, or the
game hangs. Lists every candidate; tools/gen_config.py hooks the ones in SPIN_LOOPS there.

Usage: python tools/find_spinloops.py
Output: docs/spinloops.md
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kig_funcs as kf  # noqa: E402
from kig_layout import ROOT, SEGS, recomp_rom  # noqa: E402

MAX_LEN = 12  # instructions


def find_loops():
    rom = recomp_rom()
    secs = {s.name: kf.Section(s, rom) for s in SEGS}
    funcs = list(csv.DictReader(open(ROOT / "build" / "kig_funcs.csv")))
    out = []
    seen = set()
    for r in funcs:
        sec = secs[r["section"]]
        a, size = int(r["vram"], 16), int(r["size"], 16)
        for v in range(a, a + size, 4):
            i = sec.ins(v)
            if not (i.isBranch() or i.getOpcodeName() == "j"):
                continue
            t = i.getBranchVramGeneric() if i.getOpcodeName() != "j" else i.getInstrIndexAsVram()
            if not (a <= t <= v and (v - t) // 4 < MAX_LEN):
                continue
            body = [sec.ins(x) for x in range(t, v + 8, 4)]  # including the delay slot
            names = [b.getOpcodeName() for b in body]
            if any(n.startswith("s") and b.doesStore() for n, b in zip(names, body)):
                continue
            if any(b.isJump() and n in ("jal", "jalr") for n, b in zip(names, body)):
                continue
            loads = [(x, b) for x, b in zip(range(t, v + 8, 4), body) if b.doesLoad()]
            if not loads:
                continue
            # Writes to registers that are read before being written again would make it a counting loop;
            # keep only loops whose non-load instructions don't update a register they also read (addiu x, x).
            counting = any(n in ("addiu", "addi", "addu", "subu") and b.rs.value == b.rt.value != 0
                           for n, b in zip(names, body) if n in ("addiu", "addi"))
            if counting:
                continue
            key = (r["section"], t)
            if key in seen:
                continue
            seen.add(key)
            out.append((r["section"], r["name"], t, v, [f"{x:08X}: {b.disassemble()}" for x, b in loads]))
    return out


def main() -> int:
    loops = find_loops()
    md = ["# Busy-wait loop candidates — Killer Instinct Gold", "", "Generated by `tools/find_spinloops.py`.", "",
          "| Section | Function | Head | Branch | Loads |", "|---|---|---|---|---|"]
    for s, n, t, v, loads in loops:
        md.append(f"| {s} | {n} | `{t:08X}` | `{v:08X}` | {'<br>'.join(f'`{l}`' for l in loads)} |")
    (ROOT / "docs" / "spinloops.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    for s, n, t, v, loads in loops:
        print(f"{s} {n} head {t:08X} branch {v:08X}: " + "; ".join(loads))
    return 0


if __name__ == "__main__":
    sys.exit(main())
