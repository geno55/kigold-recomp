"""Find unnamed functions that touch hardware directly or call low-level libultra internals.

N64Recomp only replaces libultra functions it knows by name (lib/N64Recomp/src/symbol_lists.cpp), so
every function that reaches hardware must carry its libultra name (or be stubbed/replaced here).
Flags per function: KSEG1 MMIO addresses (lui 0xA4xx/0xA5xx/0xBxxx), COP0 (mfc0/mtc0), cache ops, and
calls to named SI/PI/VI/SP internals.

Inputs: build/kig_funcs.csv, syms/libultra_symbols.txt, build/kig.recomp.z64
Output: docs/hw_audit.md; prints the unnamed flagged functions
Usage:  python tools/kig_hw_audit.py
"""
import csv
import re
import struct
import sys
from pathlib import Path

import rabbitizer

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kig_layout import BY_NAME, ROOT, recomp_rom  # noqa: E402
from recomp_lists import skipped_funcs  # noqa: E402

LOWLEVEL = re.compile(r"^(__osSi|__osPi|__osSp|__osVi|__osEep|__osCont|__osDisableInt|__osRestoreInt|osPiRaw|__osAi|__osDp)")


def main() -> int:
    rom = recomp_rom()
    names = {}
    for line in (ROOT / "syms" / "libultra_symbols.txt").read_text().splitlines():
        m = re.match(r"(\w+) = 0x([0-9A-F]+);", line)
        if m:
            names[int(m[2], 16)] = m[1]
    skipped = skipped_funcs()
    rows = list(csv.DictReader(open(ROOT / "build" / "kig_funcs.csv")))
    flagged = []
    for r in rows:
        seg = BY_NAME[r["section"]]
        v0, size = int(r["vram"], 16), int(r["size"], 16)
        name = names.get(v0) if r["section"] in ("boot", "seg0") else None
        if name in skipped:
            continue
        why = set()
        for v in range(v0, v0 + size, 4):
            w = struct.unpack(">I", rom[seg.recomp_rom + v - seg.vram:seg.recomp_rom + v - seg.vram + 4])[0]
            i = rabbitizer.Instruction(w, v)
            n = i.getOpcodeName()
            if n == "lui" and (0xA400 <= i.getImmediate() < 0xA600 or 0xB000 <= i.getImmediate() < 0xC000):
                why.add(f"lui {i.getImmediate():#06x}")
            elif n in ("mfc0", "mtc0", "cache", "eret", "tlbwi", "tlbp", "tlbr"):
                why.add(n)
            elif n == "jal":
                t = names.get(i.getInstrIndexAsVram())
                if t and LOWLEVEL.match(t):
                    why.add(f"calls {t}")
        if why:
            flagged.append((r["section"], v0, name or r["name"], sorted(why)))
    md = ["# Hardware access audit — Killer Instinct Gold", "", "Generated by `tools/kig_hw_audit.py`.",
          "Functions N64Recomp skips (replaced by the runtime) are not listed.", "",
          "| Section | VRAM | Function | Accesses |", "|---|---|---|---|"]
    md += [f"| {s} | `{v:08X}` | {n} | {', '.join(w)} |" for s, v, n, w in flagged]
    (ROOT / "docs" / "hw_audit.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    for s, v, n, w in flagged:
        print(f"{s} {v:08X} {n}: {', '.join(w)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
